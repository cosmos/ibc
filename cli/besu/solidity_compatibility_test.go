func mustHex(s string) []byte {
	b, err := hex.DecodeString(s)
	if err != nil {
		panic(err)
	}

	return b
}

func TestSolidityGoldenUpdateClient(t *testing.T) {
	fixture := besutest.MustFixture(t)
	update := fixture.NonAdjacentUpdate

	nodes, err := update.AccountProofNodes()
	require.NoError(t, err)

	encoded, err := besu.EncodeUpdateClient(
		update.HeaderRLP,
		update.TrustedHeight,
		fixture.InitialConsensusState(),
		nodes,
	)
	require.NoError(t, err)
	assert.Equal(t, goldenUpdateNonAdjacent, encoded)
}

func TestSolidityGoldenMembershipProofs(t *testing.T) {
	fixture := besutest.MustFixture(t)
	preimage := fixture.NonAdjacentUpdate.ExpectedConsensusState()

	for name, tc := range map[string]struct {
		fixture besutest.MembershipFixture
		golden  []byte
	}{
		"membership":    {fixture.Membership, goldenMembershipProof},
		"nonMembership": {fixture.NonMembership, goldenNonMembershipProof},
	} {
		t.Run(name, func(t *testing.T) {
			nodes, err := tc.fixture.ProofNodes()
			require.NoError(t, err)

			encoded, err := besu.EncodeMembershipProof(preimage, nodes)
			require.NoError(t, err)
			assert.Equal(t, tc.golden, encoded)
		})
	}
}

func TestSolidityGoldenConsensusStateHash(t *testing.T) {
	fixture := besutest.MustFixture(t)

	initial, err := fixture.InitialConsensusState().Hash()
	require.NoError(t, err)
	assert.Equal(t, goldenInitialConsensusHash, initial)

	installed, err := fixture.NonAdjacentUpdate.ExpectedConsensusState().Hash()
	require.NoError(t, err)
	assert.Equal(t, goldenNonAdjacentConsensusHash, installed)
}

func TestSolidityGoldenClientState(t *testing.T) {
	fixture := besutest.MustFixture(t)

	state, err := besu.DecodeClientState(goldenClientState)
	require.NoError(t, err)
	assert.Equal(t, besu.ClientState{
		IBCRouter:      fixture.RouterAddress,
		LatestHeight:   fixture.InitialTrustedHeight,
		TrustingPeriod: fixture.TrustingPeriod,
		MaxClockDrift:  fixture.MaxClockDrift,
	}, state)

	encoded, err := besutest.EncodeClientState(state)
	require.NoError(t, err)
	assert.Equal(t, goldenClientState, encoded)
}

func TestSolidityGoldenCommitmentSlot(t *testing.T) {
	fixture := besutest.MustFixture(t)
	assert.Equal(t, goldenCommitmentSlot, besu.CommitmentSlot(fixture.Membership.Path))
}
